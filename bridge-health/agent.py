#!/usr/bin/env python3
"""
AI Bridge Health Agent
======================

The swap decision is DETERMINISTIC — no AI needed:
  - Bridge has 3+ consecutive failures
  - We have a verified-alive replacement of the same transport type
  → SWAP

The AI (Qwen 2.5 3B via llama.cpp) is ONLY used to write the PR
description. If the AI fails (empty response, parse error, etc.),
a template-based PR description is used instead. The swap happens
regardless of whether the AI works.

Usage:
    python3 agent.py <health_data.json> <candidates.json> [--llama-bin PATH] [--model PATH]
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path
from datetime import datetime, timezone

LLAMA_BIN = os.environ.get("LLAMA_BIN", "llama-cli")
MODEL_PATH = os.environ.get("MODEL_PATH", "qwen2.5-3b-instruct-q4_k_m.gguf")


def make_deterministic_decisions(health_data: dict, candidates: list) -> list:
    """Make swap decisions DETERMINISTICALLY — no AI needed.

    Rules:
    1. For each dead bridge with 3+ consecutive failures
    2. Find a verified-alive replacement of the SAME transport type
    3. If found → SWAP
    4. If not found → skip (can't replace)
    """
    current = health_data.get("current_results", [])
    failure_counts = health_data.get("failure_counts", {})

    actions = []
    used_candidates = set()

    for bridge in current:
        line = bridge["line"]
        transport = bridge["transport"]
        failures = failure_counts.get(line, 0)
        status = bridge["status"]

        # Only swap if 3+ failures AND not alive
        if failures < 3 or status == "alive":
            continue

        # Find a replacement of the same transport type
        replacement = None
        for i, c in enumerate(candidates):
            if i in used_candidates:
                continue
            if c["transport"] == transport:
                replacement = c
                used_candidates.add(i)
                break

        if replacement:
            actions.append({
                "type": "swap",
                "dead_bridge_line": line,
                "replacement_bridge_line": replacement["line"],
                "reason": f"{transport} bridge failed {failures} consecutive checks. "
                          f"Replacement bootstrapped in {replacement.get('bootstrap_time', '?')}s.",
                "bootstrap_time": replacement.get("bootstrap_time", 0),
            })
            print(f"[*] SWAP: {transport} bridge (failed {failures}x) → "
                  f"replacement ({replacement.get('bootstrap_time', '?')}s)", file=sys.stderr)
        else:
            print(f"[*] SKIP: {transport} bridge failed {failures}x but no alive replacement available",
                  file=sys.stderr)

    return actions


def generate_pr_body_template(actions: list, health_data: dict) -> str:
    """Generate a PR description using a template (no AI needed).

    This is the fallback if the AI fails. It's clear, professional,
    and includes all the evidence the user needs to review.
    """
    current = health_data.get("current_results", [])
    failure_counts = health_data.get("failure_counts", {})

    lines = ["## Bridge Health AI — Auto-Swap Proposal\n"]

    for action in actions:
        dead = action["dead_bridge_line"]
        replacement = action["replacement_bridge_line"]
        transport = action.get("reason", "").split(" ")[0] if "reason" in action else "unknown"
        failures = failure_counts.get(dead, 0)

        lines.append(f"### {transport.upper()} bridge replacement\n")
        lines.append(f"**Problem:** Bridge has failed {failures} consecutive health checks.\n")
        lines.append(f"**Dead bridge:**\n```\n{dead[:100]}...\n```\n")
        lines.append(f"**Replacement (verified alive):**\n```\n{replacement[:100]}...\n```\n")
        lines.append(f"**Bootstrap time:** {action.get('bootstrap_time', '?')}s\n")
        lines.append(f"**Reason:** {action.get('reason', 'N/A')}\n")
        lines.append("")

    lines.append("## Evidence\n")
    lines.append("| Bridge | Status | Failures |")
    lines.append("|--------|--------|----------|")
    for b in current:
        status = "✅ alive" if b["status"] == "alive" else f"❌ {b['status']}"
        fc = failure_counts.get(b["line"], 0)
        ip = b["line"][:30] + "..."
        lines.append(f"| `{ip}` | {status} | {fc} |")

    lines.append("")
    lines.append("---")
    lines.append("*Auto-generated by `.github/workflows/bridge-health.yml`")
    lines.append(f"*Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}*")

    return "\n".join(lines)


def try_ai_pr_body(actions: list, health_data: dict, llama_bin: str, model_path: str) -> str:
    """Try to generate a better PR description using the local LLM.

    If this fails for ANY reason (empty response, parse error, timeout),
    fall back to the template. The swap decision is NOT affected.
    """
    # Build a simpler prompt — just "write a PR description for this swap"
    swap_summary = []
    for a in actions:
        swap_summary.append({
            "transport": a["dead_bridge_line"].split(" ")[0],
            "failures": health_data.get("failure_counts", {}).get(a["dead_bridge_line"], 0),
            "bootstrap_time": a.get("bootstrap_time", 0),
        })

    prompt = f"""Write a concise GitHub PR description for a bridge swap in a Tor Android app.

Swaps being made:
{json.dumps(swap_summary, indent=2)}

Write ONLY the PR body as markdown. Start with ## and include:
1. One sentence summary
2. What changed (bullet list)
3. Why it matters (1-2 sentences about helping censored users)

Keep it under 200 words. No code blocks."""

    with tempfile.NamedTemporaryFile(mode="w", suffix=".txt", delete=False) as f:
        f.write(prompt)
        prompt_file = f.name

    try:
        cmd = [
            llama_bin,
            "-m", model_path,
            "-f", prompt_file,
            "-n", "400",
            "--temp", "0.3",
            "--no-cnv",
            "-t", "4",
        ]

        result = subprocess.run(cmd, capture_output=True, text=True, timeout=90)

        if result.returncode != 0:
            print(f"[!] llama-cli exited {result.returncode}", file=sys.stderr)
            return generate_pr_body_template(actions, health_data)

        output = result.stdout.strip()
        if not output or len(output) < 20:
            print("[!] AI returned empty/short response — using template", file=sys.stderr)
            return generate_pr_body_template(actions, health_data)

        # Try to extract just the markdown (skip llama-cli preamble)
        # Look for the first ## heading
        idx = output.find("## ")
        if idx != -1:
            return output[idx:]
        return output

    except subprocess.TimeoutExpired:
        print("[!] AI timed out — using template", file=sys.stderr)
        return generate_pr_body_template(actions, health_data)
    except Exception as e:
        print(f"[!] AI failed: {e} — using template", file=sys.stderr)
        return generate_pr_body_template(actions, health_data)
    finally:
        try:
            os.unlink(prompt_file)
        except:
            pass


def main():
    parser = argparse.ArgumentParser(description="AI Bridge Health Agent")
    parser.add_argument("health_data", help="Path to health data JSON")
    parser.add_argument("candidates", help="Path to candidates JSON")
    parser.add_argument("--llama-bin", default=LLAMA_BIN)
    parser.add_argument("--model", default=MODEL_PATH)
    parser.add_argument("--output", default="-")
    args = parser.parse_args()

    with open(args.health_data) as f:
        health_data = json.load(f)

    try:
        with open(args.candidates) as f:
            candidates = json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        candidates = []

    # STEP 1: Make DETERMINISTIC swap decisions (no AI)
    print("[*] Making deterministic swap decisions...", file=sys.stderr)
    actions = make_deterministic_decisions(health_data, candidates)
    print(f"[*] Decided on {len(actions)} swap(s)", file=sys.stderr)

    if not actions:
        result = {
            "actions": [],
            "pr_title": "",
            "pr_body": "No bridges require replacement at this time.",
            "summary": "no changes needed",
        }
    else:
        # STEP 2: Generate PR title
        transports = list(set(a["dead_bridge_line"].split(" ")[0] for a in actions))
        pr_title = f"fix(bridges): AI swap — replace {len(actions)} dead {', '.join(transports)} bridge(s)"

        # STEP 3: Try AI for PR body, fall back to template
        print("[*] Generating PR description (AI with template fallback)...", file=sys.stderr)
        pr_body = try_ai_pr_body(actions, health_data, args.llama_bin, args.model)

        # STEP 4: Add AI signature
        if "Auto-generated" not in pr_body:
            pr_body += "\n\n---\n*Auto-generated by bridge-health workflow*"

        result = {
            "actions": actions,
            "pr_title": pr_title,
            "pr_body": pr_body,
            "summary": f"swap {len(actions)} dead bridge(s) for verified-alive replacements",
        }

    output = json.dumps(result, indent=2)
    if args.output == "-":
        print(output)
    else:
        with open(args.output, "w") as f:
            f.write(output)

    print(f"[*] Final actions: {len(result['actions'])}", file=sys.stderr)


if __name__ == "__main__":
    main()
